`timescale 1ns / 1ps

// ============================================================
// bnn_accelerator.v  --  CAN Vehicle Classifier (Fixed-Point MLP)
//
// Model    : Bayesian MLP  169 -> 16 (ReLU) -> 3  (mean weights)
// Classes  : 0=OpelAstra  1=Prototype  2=RenaultClio
// Input    : 169 int16 Q8.8 features, one per 32-bit AXI-Stream word
//            bits[15:0] = round((feat - mean) / std * 256)
// Output   : 1 uint32 word = argmax class index (0/1/2)
// Latency  : ~188 clocks (~1.5 us @ 125 MHz)
// Weights  : ../weight_extraction/verilog_headers/bnn_can_weights.vh
//            (auto-generated by weight_extraction/extract_bnn_weights.py)
// ============================================================

module bnn_accelerator (
    input  wire        aclk,
    input  wire        aresetn,

    // AXI-Stream Slave  (169 Q8.8 int16 features in)
    input  wire [31:0] s_axis_tdata,
    input  wire        s_axis_tvalid,
    output wire        s_axis_tready,
    input  wire        s_axis_tlast,

    // AXI-Stream Master (1 uint32 class index out)
    output wire [31:0] m_axis_tdata,
    output wire        m_axis_tvalid,
    input  wire        m_axis_tready,
    output wire        m_axis_tlast
);

`include "bnn_can_weights.vh"

// ---- States ----------------------------------------------------------
localparam S_IDLE      = 3'd0;
localparam S_RECV_L1   = 3'd1;
localparam S_BIAS_RELU = 3'd2;
localparam S_COMP_L2   = 3'd3;
localparam S_ARGMAX    = 3'd4;
localparam S_SEND      = 3'd5;

// ---- Registers -------------------------------------------------------
reg [2:0]  state;
reg [7:0]  feat_idx;   // current feature index (0..168)
reg [3:0]  l2_idx;     // current L1-output index for L2 (0..15)

// L1 accumulators (48-bit signed, safe for 169 x int16 x int16)
reg signed [47:0] acc1  [0:15];
// L1 ReLU activations after >>8 normalisation (32-bit signed)
reg signed [31:0] relu1 [0:15];
// L2 accumulators (64-bit signed, safe for 16 x int32 x int16)
reg signed [63:0] acc2  [0:2];

reg [31:0] out_data;
reg        out_valid;

// ---- AXI handshake ---------------------------------------------------
assign s_axis_tready = (state == S_IDLE || state == S_RECV_L1);
assign m_axis_tdata  = out_data;
assign m_axis_tvalid = out_valid;
assign m_axis_tlast  = out_valid;

wire signed [15:0] feat_in = $signed(s_axis_tdata[15:0]);

integer i;

// ---- Main FSM --------------------------------------------------------
always @(posedge aclk) begin
    if (!aresetn) begin
        state     <= S_IDLE;
        feat_idx  <= 8'd0;
        l2_idx    <= 4'd0;
        out_valid <= 1'b0;
        out_data  <= 32'd0;
        for (i = 0; i < 16; i = i + 1) begin acc1[i] <= 0; relu1[i] <= 0; end
        for (i = 0; i < 3;  i = i + 1) acc2[i] <= 0;
    end else begin
        case (state)

        // ------ IDLE: reset accumulators, wait for first feature ------
        S_IDLE: begin
            out_valid <= 1'b0;
            for (i = 0; i < 16; i = i + 1) acc1[i] <= 0;
            for (i = 0; i < 3;  i = i + 1) acc2[i] <= 0;
            feat_idx <= 8'd0;
            l2_idx   <= 4'd0;
            if (s_axis_tvalid) begin
                acc1[ 0] <= $signed(feat_in) * $signed(BNN_W1_N0[0]);
                acc1[ 1] <= $signed(feat_in) * $signed(BNN_W1_N1[0]);
                acc1[ 2] <= $signed(feat_in) * $signed(BNN_W1_N2[0]);
                acc1[ 3] <= $signed(feat_in) * $signed(BNN_W1_N3[0]);
                acc1[ 4] <= $signed(feat_in) * $signed(BNN_W1_N4[0]);
                acc1[ 5] <= $signed(feat_in) * $signed(BNN_W1_N5[0]);
                acc1[ 6] <= $signed(feat_in) * $signed(BNN_W1_N6[0]);
                acc1[ 7] <= $signed(feat_in) * $signed(BNN_W1_N7[0]);
                acc1[ 8] <= $signed(feat_in) * $signed(BNN_W1_N8[0]);
                acc1[ 9] <= $signed(feat_in) * $signed(BNN_W1_N9[0]);
                acc1[10] <= $signed(feat_in) * $signed(BNN_W1_N10[0]);
                acc1[11] <= $signed(feat_in) * $signed(BNN_W1_N11[0]);
                acc1[12] <= $signed(feat_in) * $signed(BNN_W1_N12[0]);
                acc1[13] <= $signed(feat_in) * $signed(BNN_W1_N13[0]);
                acc1[14] <= $signed(feat_in) * $signed(BNN_W1_N14[0]);
                acc1[15] <= $signed(feat_in) * $signed(BNN_W1_N15[0]);
                feat_idx <= 8'd1;
                state    <= S_RECV_L1;
            end
        end

        // ------ RECV_L1: receive features 1..168 & accumulate L1 ------
        S_RECV_L1: begin
            if (s_axis_tvalid) begin
                acc1[ 0] <= acc1[ 0] + $signed(feat_in) * $signed(BNN_W1_N0[feat_idx]);
                acc1[ 1] <= acc1[ 1] + $signed(feat_in) * $signed(BNN_W1_N1[feat_idx]);
                acc1[ 2] <= acc1[ 2] + $signed(feat_in) * $signed(BNN_W1_N2[feat_idx]);
                acc1[ 3] <= acc1[ 3] + $signed(feat_in) * $signed(BNN_W1_N3[feat_idx]);
                acc1[ 4] <= acc1[ 4] + $signed(feat_in) * $signed(BNN_W1_N4[feat_idx]);
                acc1[ 5] <= acc1[ 5] + $signed(feat_in) * $signed(BNN_W1_N5[feat_idx]);
                acc1[ 6] <= acc1[ 6] + $signed(feat_in) * $signed(BNN_W1_N6[feat_idx]);
                acc1[ 7] <= acc1[ 7] + $signed(feat_in) * $signed(BNN_W1_N7[feat_idx]);
                acc1[ 8] <= acc1[ 8] + $signed(feat_in) * $signed(BNN_W1_N8[feat_idx]);
                acc1[ 9] <= acc1[ 9] + $signed(feat_in) * $signed(BNN_W1_N9[feat_idx]);
                acc1[10] <= acc1[10] + $signed(feat_in) * $signed(BNN_W1_N10[feat_idx]);
                acc1[11] <= acc1[11] + $signed(feat_in) * $signed(BNN_W1_N11[feat_idx]);
                acc1[12] <= acc1[12] + $signed(feat_in) * $signed(BNN_W1_N12[feat_idx]);
                acc1[13] <= acc1[13] + $signed(feat_in) * $signed(BNN_W1_N13[feat_idx]);
                acc1[14] <= acc1[14] + $signed(feat_in) * $signed(BNN_W1_N14[feat_idx]);
                acc1[15] <= acc1[15] + $signed(feat_in) * $signed(BNN_W1_N15[feat_idx]);
                if (feat_idx == 8'd168)
                    state <= S_BIAS_RELU;
                else
                    feat_idx <= feat_idx + 8'd1;
            end
        end

        // ------ BIAS_RELU: add L1 bias, ReLU, normalise by >>8 -------
        // Fix: use $signed({BNN_B1[n], 8'b0}) instead of a concatenation-shift.
        // The concatenation {{{...}, BNN_B1[n]} <<< 8} produces an UNSIGNED value
        // in SystemVerilog, which would make >= 0 always true and >>> 8 unsigned.
        // $signed({BNN_B1[n], 8'b0}) is a 24-bit signed value equal to bias * 256,
        // sign-extended to 48 bits when added to acc1[n] (both signed -> correct).
        S_BIAS_RELU: begin
            relu1[ 0] <= (acc1[ 0] + $signed({BNN_B1[ 0], 8'b0})) >= 0 ? (acc1[ 0] + $signed({BNN_B1[ 0], 8'b0})) >>> 8 : 32'sd0;
            relu1[ 1] <= (acc1[ 1] + $signed({BNN_B1[ 1], 8'b0})) >= 0 ? (acc1[ 1] + $signed({BNN_B1[ 1], 8'b0})) >>> 8 : 32'sd0;
            relu1[ 2] <= (acc1[ 2] + $signed({BNN_B1[ 2], 8'b0})) >= 0 ? (acc1[ 2] + $signed({BNN_B1[ 2], 8'b0})) >>> 8 : 32'sd0;
            relu1[ 3] <= (acc1[ 3] + $signed({BNN_B1[ 3], 8'b0})) >= 0 ? (acc1[ 3] + $signed({BNN_B1[ 3], 8'b0})) >>> 8 : 32'sd0;
            relu1[ 4] <= (acc1[ 4] + $signed({BNN_B1[ 4], 8'b0})) >= 0 ? (acc1[ 4] + $signed({BNN_B1[ 4], 8'b0})) >>> 8 : 32'sd0;
            relu1[ 5] <= (acc1[ 5] + $signed({BNN_B1[ 5], 8'b0})) >= 0 ? (acc1[ 5] + $signed({BNN_B1[ 5], 8'b0})) >>> 8 : 32'sd0;
            relu1[ 6] <= (acc1[ 6] + $signed({BNN_B1[ 6], 8'b0})) >= 0 ? (acc1[ 6] + $signed({BNN_B1[ 6], 8'b0})) >>> 8 : 32'sd0;
            relu1[ 7] <= (acc1[ 7] + $signed({BNN_B1[ 7], 8'b0})) >= 0 ? (acc1[ 7] + $signed({BNN_B1[ 7], 8'b0})) >>> 8 : 32'sd0;
            relu1[ 8] <= (acc1[ 8] + $signed({BNN_B1[ 8], 8'b0})) >= 0 ? (acc1[ 8] + $signed({BNN_B1[ 8], 8'b0})) >>> 8 : 32'sd0;
            relu1[ 9] <= (acc1[ 9] + $signed({BNN_B1[ 9], 8'b0})) >= 0 ? (acc1[ 9] + $signed({BNN_B1[ 9], 8'b0})) >>> 8 : 32'sd0;
            relu1[10] <= (acc1[10] + $signed({BNN_B1[10], 8'b0})) >= 0 ? (acc1[10] + $signed({BNN_B1[10], 8'b0})) >>> 8 : 32'sd0;
            relu1[11] <= (acc1[11] + $signed({BNN_B1[11], 8'b0})) >= 0 ? (acc1[11] + $signed({BNN_B1[11], 8'b0})) >>> 8 : 32'sd0;
            relu1[12] <= (acc1[12] + $signed({BNN_B1[12], 8'b0})) >= 0 ? (acc1[12] + $signed({BNN_B1[12], 8'b0})) >>> 8 : 32'sd0;
            relu1[13] <= (acc1[13] + $signed({BNN_B1[13], 8'b0})) >= 0 ? (acc1[13] + $signed({BNN_B1[13], 8'b0})) >>> 8 : 32'sd0;
            relu1[14] <= (acc1[14] + $signed({BNN_B1[14], 8'b0})) >= 0 ? (acc1[14] + $signed({BNN_B1[14], 8'b0})) >>> 8 : 32'sd0;
            relu1[15] <= (acc1[15] + $signed({BNN_B1[15], 8'b0})) >= 0 ? (acc1[15] + $signed({BNN_B1[15], 8'b0})) >>> 8 : 32'sd0;
            l2_idx <= 4'd0;
            state  <= S_COMP_L2;
        end

        // ------ COMP_L2: accumulate L2 (16 steps, 3 MACs parallel) ---
        S_COMP_L2: begin
            acc2[0] <= acc2[0] + $signed(relu1[l2_idx]) * $signed(BNN_W2_M0[l2_idx]);
            acc2[1] <= acc2[1] + $signed(relu1[l2_idx]) * $signed(BNN_W2_M1[l2_idx]);
            acc2[2] <= acc2[2] + $signed(relu1[l2_idx]) * $signed(BNN_W2_M2[l2_idx]);
            if (l2_idx == 4'd15)
                state <= S_ARGMAX;
            else
                l2_idx <= l2_idx + 4'd1;
        end

        // ------ ARGMAX: add L2 bias, compare logits, output class ----
        // Same signed fix: $signed({BNN_B2[m], 8'b0}) gives correct signed bias*256.
        S_ARGMAX: begin
            begin : argmax_blk
                reg signed [63:0] lb0, lb1, lb2;
                lb0 = acc2[0] + $signed({BNN_B2[0], 8'b0});
                lb1 = acc2[1] + $signed({BNN_B2[1], 8'b0});
                lb2 = acc2[2] + $signed({BNN_B2[2], 8'b0});
                if      (lb0 >= lb1 && lb0 >= lb2) out_data <= 32'd0;  // OpelAstra
                else if (lb1 >= lb2)               out_data <= 32'd1;  // Prototype
                else                               out_data <= 32'd2;  // RenaultClio
            end
            out_valid <= 1'b1;
            state     <= S_SEND;
        end

        // ------ SEND: hold output until master accepts ----------------
        S_SEND: begin
            if (m_axis_tready && out_valid) begin
                out_valid <= 1'b0;
                state     <= S_IDLE;
            end
        end

        default: state <= S_IDLE;
        endcase
    end
end

endmodule
